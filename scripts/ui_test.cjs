const fs=require('fs');
const path=require('path');
const {chromium}=require('C:/Users/35100/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root=path.resolve(__dirname,'..');
const output=path.join(root,'deliverables');fs.mkdirSync(output,{recursive:true});
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:8765');
 await page.locator('.home h1').waitFor();
 await page.screenshot({path:path.join(output,'ui-home.png'),fullPage:true});
 await page.locator('input[type=file]').setInputFiles(path.join(root,'samples/digital.pdf'));
 await page.getByRole('button',{name:'自动还原 2 页',exact:true}).waitFor();
 await page.getByRole('button',{name:'自动还原 2 页',exact:true}).click();
 await page.getByText('处理完成，请检查需要校正的图层',{exact:true}).waitFor({timeout:180000});
 await page.locator('.layer-select').filter({hasText:'收入 128.50 万元'}).click();
 await page.getByRole('tab',{name:'属性',exact:true}).click();
 await page.locator('#text-edit').fill('收入 999.00 万元');
 await page.getByText('已保存',{exact:true}).waitFor();
 await page.getByRole('button',{name:'撤销 Ctrl+Z',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#text-edit')?.value==='收入 128.50 万元',{},{timeout:5000});
 await page.getByText('已保存',{exact:true}).waitFor();
 if(await page.locator('#text-edit').inputValue()!=='收入 128.50 万元')throw new Error('Undo did not restore text: '+JSON.stringify(await page.locator('#text-edit').inputValue()));
 await page.getByRole('tab',{name:/^图层/}).click();
 await page.getByRole('group',{name:'图层筛选'}).getByRole('button',{name:'文字',exact:true}).click();
 await page.getByRole('tab',{name:'属性',exact:true}).click();
 await page.getByLabel('字体',{exact:true}).fill('Microsoft YaHei');
 await page.getByLabel('字号',{exact:true}).fill('6');
 await page.getByLabel('字间距',{exact:true}).fill('0.3');
 await page.getByRole('button',{name:'粗体',exact:true}).click();
 await page.getByText('已保存',{exact:true}).waitFor();
 if(await page.getByRole('button',{name:'粗体',exact:true}).getAttribute('aria-pressed')!=='true')throw new Error('Bold state did not update');
 await page.getByRole('button',{name:'移开检查',exact:true}).click();
 await page.screenshot({path:path.join(output,'ui-editor.png'),fullPage:true});
 await page.getByRole('button',{name:'移开检查',exact:true}).click();
 const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'导出 PPTX',exact:true}).click();
 const download=await downloadEvent;await download.saveAs(path.join(output,'browser-export.pptx'));
 await page.getByRole('button',{name:'返回项目',exact:true}).click();
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(output,'ui-mobile.png'),fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 fs.writeFileSync(path.join(output,'ui-test.json'),JSON.stringify({errors,mobileOverflow:overflow,import:true,convert:true,textEdit:true,undo:true,smallFontSize:6,fontFamily:true,bold:true,characterSpacing:.3,textLayerFilter:true,export:true},null,2));
 await browser.close();if(errors.length||overflow)throw new Error(JSON.stringify({errors,overflow}));
 console.log('UI end-to-end passed');
})().catch(e=>{console.error(e);process.exit(1)});
